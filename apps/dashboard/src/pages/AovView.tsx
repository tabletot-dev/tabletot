import { useState, useEffect, useCallback } from 'react';
import { supabase } from '@/integrations/supabase/client';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Button } from '@/components/ui/button';
import { Loader2, AlertTriangle } from 'lucide-react';
import { FeatureGate } from '@/components/FeatureGate';
import { formatRupees } from '@/lib/formatCurrency';

const RESTAURANT_ID = import.meta.env.VITE_RESTAURANT_ID as string;

type DateRange = '7d' | '14d' | 'all';

interface AcceptedItem {
  item_name: string;
  count: number;
  revenue: number;
}

interface AovSummary {
  accepted_count: number | null;
  direct_revenue: number | null;
  accepted_items: AcceptedItem[] | null;
  total_revenue: number | null;
  session_count: number | null;
}

function dateRangeParams(range: DateRange): { start: string; end: string } {
  const now = new Date();
  const end = now.toISOString();
  if (range === '7d') {
    const start = new Date(now.getTime() - 7 * 24 * 60 * 60 * 1000).toISOString();
    return { start, end };
  }
  if (range === '14d') {
    const start = new Date(now.getTime() - 14 * 24 * 60 * 60 * 1000).toISOString();
    return { start, end };
  }
  return { start: '2000-01-01T00:00:00Z', end };
}

export default function AovView() {
  const [data, setData] = useState<AovSummary | null>(null);
  const [loading, setLoading] = useState(true);
  // A failed query previously fell through to `data === null` → the same
  // render path as "0 accepted", so a broken RPC and an honest zero were
  // indistinguishable on the headline number shown to the restaurant owner.
  const [error, setError] = useState<string | null>(null);
  const [range, setRange] = useState<DateRange>('7d');

  const fetchSummary = useCallback(async (r: DateRange) => {
    setLoading(true);
    setError(null);
    const { start, end } = dateRangeParams(r);
    const { data: rows, error: rpcError } = await supabase.rpc('get_aov_summary' as never, {
      p_restaurant_id: RESTAURANT_ID,
      p_start_at: start,
      p_end_at: end,
    } as never);
    if (rpcError) {
      setError(rpcError.message);
      setData(null);
    } else {
      setData((rows as AovSummary[] | null)?.[0] ?? null);
    }
    setLoading(false);
  }, []);

  useEffect(() => {
    fetchSummary(range);
  }, [range, fetchSummary]);

  const acceptedItems = data?.accepted_items ?? [];
  const directRevenue = data?.direct_revenue ?? 0;
  const acceptedCount = data?.accepted_count ?? 0;
  const totalRevenue = data?.total_revenue ?? 0;
  const sessionCount = data?.session_count ?? 0;

  return (
    <FeatureGate requiredProvider="tabletot">
      <div className="p-6 max-w-3xl mx-auto space-y-6">
        <div className="flex items-start justify-between gap-4 flex-wrap">
          <div>
            <h1 className="text-2xl font-bold">AOV Impact</h1>
            <p className="text-muted-foreground text-sm mt-1">
              Direct revenue Tabletot generated by converting recommendation taps into orders,
              plus a snapshot of overall revenue and sessions in the window.
            </p>
          </div>
          <div className="flex gap-2">
            {(['7d', '14d', 'all'] as DateRange[]).map((r) => (
              <Button
                key={r}
                variant={range === r ? 'default' : 'outline'}
                size="sm"
                onClick={() => setRange(r)}
              >
                {r === '7d' ? 'Last 7d' : r === '14d' ? 'Last 14d' : 'All time'}
              </Button>
            ))}
          </div>
        </div>

        <Card>
          <CardHeader>
            <CardTitle>Direct revenue from recommendations</CardTitle>
          </CardHeader>
          <CardContent>
            {loading ? (
              <div className="flex items-center gap-2 text-muted-foreground text-sm">
                <Loader2 className="h-4 w-4 animate-spin" /> Loading…
              </div>
            ) : error ? (
              <div className="flex flex-col items-center gap-2 py-4 text-center">
                <p className="flex items-center gap-2 text-sm text-destructive">
                  <AlertTriangle className="h-4 w-4" /> Couldn't load this data — not a real zero.
                </p>
                <p className="text-xs text-muted-foreground">{error}</p>
                <Button variant="outline" size="sm" onClick={() => fetchSummary(range)}>Retry</Button>
              </div>
            ) : acceptedCount === 0 ? (
              <p className="text-muted-foreground text-sm py-4 text-center">
                No recommendations accepted in this date range yet.
              </p>
            ) : (
              <div className="space-y-4">
                <div>
                  <p className="text-3xl font-bold text-emerald-600">{formatRupees(directRevenue)}</p>
                  <p className="text-sm text-muted-foreground mt-1">
                    directly generated from {acceptedCount} accepted recommendation
                    {acceptedCount === 1 ? '' : 's'}
                  </p>
                </div>

                <div className="rounded-lg border divide-y">
                  <div className="grid grid-cols-[1fr_auto_auto] gap-4 px-4 py-2 text-xs text-muted-foreground uppercase tracking-wide bg-muted/30">
                    <span>Item</span>
                    <span className="text-right">Accepted</span>
                    <span className="text-right">Revenue</span>
                  </div>
                  {acceptedItems.map((row) => (
                    <div
                      key={row.item_name}
                      className="grid grid-cols-[1fr_auto_auto] gap-4 px-4 py-2 text-sm"
                    >
                      <span className="font-medium">{row.item_name}</span>
                      <span className="text-right text-muted-foreground">×{row.count}</span>
                      <span className="text-right font-semibold">{formatRupees(row.revenue)}</span>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </CardContent>
        </Card>

        <Card>
          <CardHeader>
            <CardTitle>Revenue snapshot</CardTitle>
          </CardHeader>
          <CardContent>
            {loading ? (
              <div className="flex items-center gap-2 text-muted-foreground text-sm">
                <Loader2 className="h-4 w-4 animate-spin" /> Loading…
              </div>
            ) : error ? (
              <div className="flex flex-col items-center gap-2 py-4 text-center">
                <p className="flex items-center gap-2 text-sm text-destructive">
                  <AlertTriangle className="h-4 w-4" /> Couldn't load this data.
                </p>
                <Button variant="outline" size="sm" onClick={() => fetchSummary(range)}>Retry</Button>
              </div>
            ) : (
              <div className="grid grid-cols-2 gap-4">
                <div className="rounded-lg border p-4">
                  <p className="text-xs text-muted-foreground uppercase tracking-wide">
                    Total revenue
                  </p>
                  <p className="text-2xl font-bold mt-1">{formatRupees(totalRevenue)}</p>
                  <p className="text-xs text-muted-foreground">across all orders in window</p>
                </div>
                <div className="rounded-lg border p-4">
                  <p className="text-xs text-muted-foreground uppercase tracking-wide">
                    Sessions
                  </p>
                  <p className="text-2xl font-bold mt-1">{sessionCount}</p>
                  <p className="text-xs text-muted-foreground">customer visits in window</p>
                </div>
              </div>
            )}
          </CardContent>
        </Card>
      </div>
    </FeatureGate>
  );
}
